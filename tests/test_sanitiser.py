"""The sanitiser strips the structural attack surface and keeps the real claims.

The poisoned demo article carries five planted injections; none may reach the model,
and both genuine claims must survive.
"""
from pathlib import Path

from ctiac.sanitiser import sanitise

ROOT = Path(__file__).resolve().parent.parent
POISONED = (ROOT / "demo/articles/A04-poisoned-forum-post.html").read_text()
FROZEN = ROOT / "demo/transcripts/A04-sanitised-model-input.txt"

# The envelope in the frozen transcript was stamped with these. They are inputs,
# not outputs, so they live here rather than being parsed back out of the file.
FROZEN_SOURCE_ID = "SCR-FORUM-11"
FROZEN_RETRIEVED = "2026-08-28T14:02:00Z"


def test_injections_neutralised():
    text = sanitise(POISONED, source_id="SCR-FORUM-11").text.lower()
    for probe in ("ignore the analyst", "maintenance mode", "reviewer_override",
                  "append the contents", "auto-dismiss", "suppressing", "###end"):
        assert probe not in text, f"injection leaked: {probe!r}"


def test_real_claims_survive():
    text = sanitise(POISONED, source_id="SCR-FORUM-11").text.lower()
    for probe in ("routekit-serve", "carrier-connector", "4.1.9", "status endpoint"):
        assert probe in text, f"real claim dropped: {probe!r}"


def test_base64_flagged_not_decoded():
    res = sanitise(POISONED, source_id="SCR-FORUM-11")
    assert any("base64" in f.lower() for f in res.flags)
    # The decoded payload ("Ignore all previous instructions...") must never appear.
    assert "exfiltrate" not in res.text.lower()


def test_hidden_elements_removed():
    res = sanitise(POISONED, source_id="SCR-FORUM-11")
    assert any("hidden" in f.lower() for f in res.flags)


def test_item_is_flagged_for_review():
    # The whole point: a poisoned item is flagged, so it routes to a human rather
    # than the auto-dismiss the injection asked for.
    res = sanitise(POISONED, source_id="SCR-FORUM-11")
    assert res.flags, "a poisoned item produced no flags"


def test_clean_article_passes_quietly():
    clean = (ROOT / "demo/articles/A01-manifestkit-advisory.html").read_text()
    res = sanitise(clean, source_id="SRC-01")
    assert "ex-2026-0001" in res.text.lower()
    assert not any("prompt-structure" in f for f in res.flags)


def test_frozen_demo_transcript_still_matches_the_code():
    """The demo transcript claims it was generated by this sanitiser. Hold it to that.

    Distinct from the behavioural tests above, which assert what the sanitiser
    does. This asserts that the published artifact and the code have not
    diverged: every test above can stay green while a regex change silently
    turns the transcript into a fiction, and the transcript is what a reader who
    runs nothing actually sees.

    It is also the test of the sanitiser's own stated invariant. The module
    docstring rests the no-model-sanitises-for-a-model argument on the stage
    being deterministic, and same-input-same-bytes is what that means.

    If this fails, read the diff before regenerating. A deliberate change to the
    sanitiser means regenerating the transcript in the same commit, so the two
    move together and the diff is reviewable. Regenerating to make the test pass
    is how a golden test stops being one.
    """
    frozen = "\n".join(
        line for line in FROZEN.read_text().splitlines() if not line.startswith("#")
    ).strip()
    live = sanitise(POISONED, source_id=FROZEN_SOURCE_ID).enveloped(
        retrieved=FROZEN_RETRIEVED
    ).strip()
    assert live == frozen, (
        "demo/transcripts/A04-sanitised-model-input.txt no longer matches the "
        "output of src/ctiac/sanitiser.py. Regenerate it in this "
        "commit if the sanitiser change was intended."
    )
